#!/usr/bin/env python3
"""Regenerate js/photos.js from assets/photos/<driver-id>.jpg.

The app embeds portraits as data URLs so that canvas export never hits
cross-origin restrictions. Replace any file in assets/photos (keep the
driver id as the filename) and run:

    python tools/build_photos.py

Requires Pillow (pip install pillow).
"""
from __future__ import annotations

import base64
import io
import os
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required:  pip install pillow")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "photos")
OUT = os.path.join(ROOT, "js", "photos.js")
TARGET_WIDTH = 340
QUALITY = 82
VALID_EXT = {".jpg", ".jpeg", ".png", ".webp"}


def main() -> int:
    if not os.path.isdir(SRC):
        sys.exit(f"missing folder: {SRC}")

    entries = []
    for name in sorted(os.listdir(SRC)):
        stem, ext = os.path.splitext(name)
        if ext.lower() not in VALID_EXT:
            continue
        path = os.path.join(SRC, name)
        try:
            with Image.open(path) as im:
                im = im.convert("RGB")
                width = min(TARGET_WIDTH, im.width)
                height = round(im.height * width / im.width)
                im = im.resize((width, height), Image.LANCZOS)
                buf = io.BytesIO()
                im.save(buf, "JPEG", quality=QUALITY, optimize=True, progressive=True)
                data = buf.getvalue()
                b64 = base64.b64encode(data).decode("ascii")
                entries.append((stem, "data:image/jpeg;base64," + b64))
                print(f"  {stem:<12} {width}x{height}  {len(data) / 1024:5.1f} KB")
        except Exception as exc:  # noqa: BLE001
            print(f"  skip {name}: {exc}")

    if not entries:
        sys.exit("no images found in assets/photos")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build_photos.py — driver portrait data URLs.\n")
        fh.write("   Sources: Wikimedia Commons (see CREDITS.md). Replace a photo in the app UI\n")
        fh.write("   or regenerate this file with your own images. */\n")
        fh.write("window.F1AGE_PHOTOS = {\n")
        for driver_id, data_url in entries:
            fh.write(f"  {driver_id}: '{data_url}',\n")
        fh.write("};\n")

    size_kb = os.path.getsize(OUT) / 1024
    print(f"\nwrote {OUT}  ({len(entries)} photos, {size_kb:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
